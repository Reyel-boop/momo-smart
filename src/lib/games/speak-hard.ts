const DEESCALATE = (customer: string, sample: string) =>
  step(
    "De-escalate",
    customer,
    "Stay calm. Apologize, show you understand, and take ownership: say YOU will handle it.",
    sample,
    [SORRY, EMPATHY, OWNERSHIP],
  );
const VERIFY_STEP = (customer: string) =>
  step(
    "Verification",
    customer,
    "Politely ask for the account number and the account holder's full name.",
    "Thank you. May I have your account number and the full name of the account holder, please?",
    [POLITE, VERIFY],
  );
